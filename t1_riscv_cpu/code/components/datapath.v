// datapath.v
module datapath (
    input         clk, reset,
    input [1:0]   ResultSrc,
    input         PCSrc, ALUSrc,
    input         RegWrite,
    input [1:0]   ImmSrc,
    input [3:0]   ALUControl,
    input         Jalr,
    output        Zero,
    output [31:0] PC,
    input  [31:0] Instr,
    output [31:0] Mem_WrAddr, Mem_WrData,
    input  [31:0] ReadData,
    output [31:0] Result
);

// PCJalr: final next PC after selecting between normal PC path and jalr target
// PCNext: next PC selected between PCPlus4 and branch or jal target
// PCPlus4: sequential instruction address
// PCTarget: branch or jal target address generated from PC and immedeate
// AuiPC: AUIPC result generated by adding upper immedeate to PC
// lAuiPC: result selected between AUIPC and LUI data

wire [31:0] PCJalr, PCNext, PCPlus4, PCTarget, AuiPC, lAuiPC;

// ImmExt: extended immediate value generated from the current instruction
// SrcA: first source operand read from the register file
// SrcB: second ALU operand selected between register data and immediate
// WriteData: second register file read data used by stores and branches
// ALUResult: output of the ALU used as address, arithmetic result or jalr target

wire [31:0] ImmExt, SrcA, SrcB, WriteData, ALUResult;

// LoadResult: final data to be written back for load instructions
// StoreData: final data sent to data memory for store instructions

wire [31:0] LoadResult, StoreData;

// alu_zero: zero flag generated by the ALU for arithmetic comparison result
wire        alu_zero;

// next PC logic

mux2 #(32)     pcmux(PCPlus4, PCTarget, PCSrc, PCNext);
mux2 #(32)     jalrmux (PCNext, ALUResult, Jalr, PCJalr);

reset_ff #(32) pcreg(clk, reset, PCJalr, PC);
adder          pcadd4(PC, 32'd4, PCPlus4);
adder          pcaddbranch(PC, ImmExt, PCTarget);

// register file logic
reg_file       rf (clk, RegWrite, Instr[19:15], Instr[24:20], Instr[11:7], Result, SrcA, WriteData);
imm_extend     ext (Instr[31:7], ImmSrc, ImmExt);

// branch condition (beq, bne, blt, bge, bltu, bgeu)
wire [2:0] funct3 = Instr[14:12];
wire eq  = (SrcA == WriteData);
wire lt  = ($signed(SrcA) < $signed(WriteData));
wire ltu = (SrcA < WriteData);

wire branch_taken = ((funct3 == 3'b000) &  eq)    // beq
                  | ((funct3 == 3'b001) & ~eq)    // bne
                  | ((funct3 == 3'b100) &  lt)    // blt
                  | ((funct3 == 3'b101) & ~lt)    // bge
                  | ((funct3 == 3'b110) &  ltu)   // bltu
                  | ((funct3 == 3'b111) & ~ltu);  // bgeu

assign Zero = branch_taken;

// ALU logic
mux2 #(32)     srcbmux(WriteData, ImmExt, ALUSrc, SrcB);
alu            alu (SrcA, SrcB, ALUControl, ALUResult, alu_zero);

adder #(32)    auipcadder ({Instr[31:12], 12'b0}, PC, AuiPC);
mux2 #(32)     lauipcmux (AuiPC, {Instr[31:12], 12'b0}, Instr[5], lAuiPC);

// load / store byte halfword handling
load_unit  lu (
    .ReadData   (ReadData),
    .addr       (ALUResult[1:0]),
    .funct3     (funct3),
    .LoadResult (LoadResult)
);

store_unit su (
    .ReadData   (ReadData),
    .WriteData  (WriteData),
    .addr       (ALUResult[1:0]),
    .funct3     (funct3),
    .StoreData  (StoreData)
);

// Result source
mux4 #(32)     resultmux(ALUResult, LoadResult, PCPlus4, lAuiPC, ResultSrc, Result);

assign Mem_WrData = StoreData;
assign Mem_WrAddr = ALUResult;

endmodule