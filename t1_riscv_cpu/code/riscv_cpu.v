// riscv_cpu.v - single cycle riscv cpu

module riscv_cpu (
    input         clk, reset,
    output [31:0] PC,
    input  [31:0] Instr,
    output        MemWrite,
    output [31:0] Mem_WrAddr, Mem_WrData,
    input  [31:0] ReadData,
    output [31:0] Result
);

// ALUSrc: selects register or immediate input for the second ALU operand
// RegWrite: enables register file writeback
// Jump: indicates jal instruction control flow
// Jalr: indicates jalr instruction control flow
// Zero: branch condition result generated by the datapath

wire        ALUSrc, RegWrite, Jump, Jalr, Zero;

// ResultSrc: selects the value written back to the register file
// ImmSrc: selects the immediate format for extension

wire [1:0]  ResultSrc, ImmSrc;

// ALUControl: encoded control signal selecting the ALU operation

wire [3:0]  ALUControl;

controller  c   (Instr[6:0], Instr[14:12], Instr[30], Zero,
                ResultSrc, MemWrite, PCSrc, ALUSrc, RegWrite, Jump, Jalr,
                ImmSrc, ALUControl);

datapath    dp  (clk, reset, ResultSrc, PCSrc,
                ALUSrc, RegWrite, ImmSrc, ALUControl, Jalr,
                Zero, PC, Instr, Mem_WrAddr, Mem_WrData, ReadData, Result);

endmodule

