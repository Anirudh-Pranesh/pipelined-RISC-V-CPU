// pl_riscv_cpu.v - top-level pipelined RISC-V CPU and memories

module pl_riscv_cpu (
    // clk: processor clock
    // reset: processor reset signal
    input         clk, reset,
    // Ext_MemWrite: external memory write enable used during memory initialization
    // Ext_WriteData: external data written to memory during initialization
    // Ext_DataAdr: external memory address used during initialization
    input         Ext_MemWrite,
    input  [31:0] Ext_WriteData, Ext_DataAdr,
    // MemWrite: memory write observation signal
    output        MemWrite,
    // WriteData: external write data observation signal
    // DataAdr: external address observation signal
    // ReadData: data returned by data memory
    output [31:0] WriteData, DataAdr, ReadData,
    // PCW: program counter of instruction in writeback
    // Result: final writeback result
    // ALUResultW: writeback ALU or address result
    // WriteDataW: writeback store data
    output [31:0] PCW, Result, ALUResultW, WriteDataW
);

// Instr: instruction fetched from instruction memory
// PC: current program counter supplied by the CPU
wire [31:0] Instr, PC;
// DataAdrM: memory stage address generated by the CPU
// WriteDataM: memory stage store data generated by the CPU
wire [31:0] DataAdrM, WriteDataM;
// DataAdrW_rv32: writeback address or debug result from the CPU
// WriteDataW_rv32: writeback store data or debug result from the CPU
wire [31:0] DataAdrW_rv32, WriteDataW_rv32;
// Funct3M: memory stage load or store operation type
// MemWriteM: memory stage store enable
// MemWriteW_rv32: writeback stage store indicator
wire [2:0]  Funct3M;
wire        MemWriteM, MemWriteW_rv32;
// StoreM: final load or store type supplied to data memory
wire [2:0]  StoreM;
// MemWriteToMemory: final memory write enable after external override selection
wire        MemWriteToMemory;

// instantiate the five-stage pipelined CPU
riscv_cpu rvcpu(
    .clk(clk),
    .reset(reset),
    .PC(PC),
    .Instr(Instr),
    .MemWrite(MemWriteM),
    .Mem_WrAddr(DataAdrM),
    .Mem_WrData(WriteDataM),
    .ReadData(ReadData),
    .Result(Result),
    .funct3(Funct3M),
    .PCW(PCW),
    .ALUResultW(DataAdrW_rv32),
    .WriteDataW(WriteDataW_rv32),
    .MemWriteW(MemWriteW_rv32)
);

// supply the instruction corresponding to the current program counter
instr_mem instrmem(PC, Instr);

// select external initialization values or normal CPU memory values
assign StoreM = (Ext_MemWrite && reset) ? 3'b010 : Funct3M;
assign MemWriteToMemory = (Ext_MemWrite && reset) ? 1'b1 : MemWriteM;
assign DataAdr = reset ? Ext_DataAdr : DataAdrW_rv32;
assign WriteData = (Ext_MemWrite && reset) ? Ext_WriteData : WriteDataW_rv32;
assign MemWrite = (Ext_MemWrite && reset) ? 1'b1 : MemWriteW_rv32;
// expose writeback debug values
assign ALUResultW = DataAdrW_rv32;
assign WriteDataW = WriteDataW_rv32;

// instantiate data memory for load and store operations
data_mem datamem(
    .clk(clk),
    .wr_en(MemWriteToMemory),
    .funct3(StoreM),
    .wr_addr(DataAdrM),
    .wr_data(WriteDataM),
    .rd_data_mem(ReadData)
);

endmodule
